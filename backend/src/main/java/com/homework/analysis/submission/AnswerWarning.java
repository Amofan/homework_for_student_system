package com.homework.analysis.submission;

/**
 * 答卷校对阶段可能出现的警告码。
 *
 * <p>为什么答卷不像整卷导入那样只留几个字符串常量：这里的每一个码都对应一种"教师必须做个决定"
 * 的情形，而决定的方式各不相同（有的要重新拍一页、有的要把区域拖进另一个题框、有的只要点确认）。
 * 集中成一个枚举，界面就能按码穷举地给出处理入口；漏掉一个码会在编译期暴露，
 * 而漏掉一个字符串常量只会在某条分支上安静地没有提示。
 *
 * <p>警告不是错误：出现警告的答卷照样能确认入库，只是教师必须先看过它们。
 * 唯一的例外是识别失败（{@link #OCR_FAILED}）——那一页根本没有区域可归类。
 *
 * <p>**任何一条都不允许"顺手跳过"**：识别出来的每一块区域最终要么挂在某道题下面，
 * 要么带着 {@link #ANSWER_OUT_OF_BOX} 留在界面上等教师处理，不存在第三条路。
 */
public enum AnswerWarning {

    // ---------- 整份答卷级别：影响的是"哪一页对哪一页"，不是某一道题 ----------

    /** 模板上有这一页，答卷里没找到学生交的那一页（少拍、漏传）。这道题会落成空白候选。 */
    PAGE_MISSING,

    /** 两页答卷都对上了同一个模板页：多半是同一张纸拍了两遍，或者是拍重了。 */
    PAGE_DUPLICATE,

    /** 这一页没对上任何模板页。它的区域不会自动归属，需要教师手工归类。 */
    TEMPLATE_MISMATCH,

    /** 整份答卷都没有模板可用（这份作业还没有确认入库的题目）。识别照常，但区域不带题号。 */
    TEMPLATE_MISSING,

    /** 有区域的作答落在所有题框之外——既没被任何题框盖住，也没有识别出题号。 */
    ANSWER_OUT_OF_BOX,

    /** 有页面的识别还没跑完，这次物化只包含已经出的结果。 */
    OCR_INCOMPLETE,

    /** 有页面的识别失败了，那一页没有区域。原因见失败的文档。 */
    OCR_FAILED,

    // ---------- 单道题级别：教师改一条候选就能解决 ----------

    /** 这道题名下没有任何区域。可能是学生没做，也可能是答案没被识别出来。 */
    ANSWER_BLANK,

    /** 这道题的作答跨了不止一页（学生在两页上续写）。两页的区域都在，别只批一半。 */
    CROSS_PAGE_ANSWER,

    /**
     * 这道题的区域归属不确定：区域同时压在两个题框上，或者识别出的题号与几何位置不一致。
     *
     * <p>不自动二选一，是因为选错的后果是"把这道题的解答算到另一道题头上"，
     * 而学生看到的只会是自己的分数变低。
     */
    QUESTION_AMBIGUOUS,

    /** 这道题里有识别置信度偏低的文本块。手写体的识别错误多半是错字而不是错题，读一眼就能定。 */
    LOW_CONFIDENCE,

    /** 这道题里有识别置信度偏低的公式。公式认错一个符号，整道题的解答就变成另一个意思。 */
    LOW_CONFIDENCE_FORMULA,

    /** 这道题的答案图没能自动裁出来（区域太窄）。区域与识别文字都还在，可以手工修框后重裁。 */
    ANSWER_CROP_FAILED
}
